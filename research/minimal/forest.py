"""Conservative reset models, and combs with a common congruence pair.

Forest-order membership in the reset variety is a generic mathematical
theorem in reset.tex. The finite lifting procedure is an independent check:
it tests whether evaluation factors through the entire free reset algebra.
"""

from itertools import product


def laws(op):
    n = len(op)
    return (all(op[op[x][y]][x] == op[y][x] for x, y in product(range(n), repeat=2))
            and all(op[x][op[y][z]] == op[y][op[x][z]]
                    for x, y, z in product(range(n), repeat=3)))


def conservative_tables(n):
    pairs = [(i, j) for i in range(n) for j in range(n) if i != j]
    for bits in product((False, True), repeat=len(pairs)):
        table = [[i for _ in range(n)] for i in range(n)]
        for (i, j), bit in zip(pairs, bits):
            table[i][j] = j if bit else i
        yield tuple(tuple(row) for row in table)


def forest_tables(n):
    """Enumerate parent maps independently, rejecting directed cycles."""
    for parents in product(range(n + 1), repeat=n):
        ancestors = []
        for start in range(n):
            reached, current = set(), start
            while current != n and current not in reached:
                reached.add(current)
                current = parents[current]
            if current != n:
                break
            ancestors.append(reached)
        if len(ancestors) == n:
            yield tuple(tuple(x if x in ancestors[y] else y for y in range(n))
                        for x in range(n))


def lift_free(op):
    """Whether all reset equations hold; also return the free-algebra size.

    One generator per element tests every valuation. Full status tables
    are bit-packed. Distinct values at one table give a failing equation;
    closure without a conflict gives a surjective homomorphism F_n -> op.
    """
    n = len(op)
    block = (1 << n) - 1
    masks = [sum(block << (n * s) for s in range(1 << n) if s & (1 << j))
             for j in range(n)]
    forms = [sum(1 << (n * s + j) for s in range(1 << n)) for j in range(n)]
    roots, values = list(range(n)), list(range(n))
    indices = {form: j for j, form in enumerate(forms)}
    current = 0
    while current < len(forms):
        for other in range(current + 1):
            pairs = ((current, other),) if other == current else ((current, other), (other, current))
            for a, b in pairs:
                form = forms[b] | (forms[a] & masks[roots[b]])
                value = op[values[a]][values[b]]
                old = indices.get(form)
                if old is not None:
                    if values[old] != value:
                        return False, len(forms)
                else:
                    indices[form] = len(forms)
                    forms.append(form)
                    roots.append(roots[b])
                    values.append(value)
        current += 1
    return True, len(forms)


def comb(n):
    """n >= 1 levels: base=0, sides=1..n, spines=n+1..2n."""
    assert n >= 1
    size = 2 * n + 1
    table = [[y for y in range(size)] for _ in range(size)]
    for i in range(n):
        spine = n + 1 + i
        table[spine][0] = spine
        for j in range(n):
            table[spine][1 + j] = spine if j <= i else 1 + j
            table[spine][n + 1 + j] = n + 1 + max(i, j)
    return tuple(tuple(row) for row in table)


def principal(op, a, b):
    """Compute the principal congruence generated by a=b."""
    n = len(op)
    parent = list(range(n))
    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    parent[a] = b
    changed = True
    while changed:
        changed = False
        for x, y in product(range(n), repeat=2):
            if find(x) != find(y):
                continue
            for z in range(n):
                for u, v in ((op[x][z], op[y][z]), (op[z][x], op[z][y])):
                    u, v = find(u), find(v)
                    if u != v:
                        parent[u] = v
                        changed = True
    return tuple(find(x) for x in range(n))
