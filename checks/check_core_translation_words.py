"""Audit the normal-form proof for one fixed opposite translation.

For each stored model, choice pair and fixed parameter, close the complete
finite transformation monoid generated by every translation of the first
choice and the fixed translation of the second. Check the normalizer on
every discovered transition, all powers, and the full sandwich band.
Also check commutation after adjoining a common parameter bound and the
normalized maps on every principal filter. The unrestricted statements
have written proofs in the core appendix.
"""

from collections import Counter
from itertools import permutations, product

from check_core_alternating_translations import compose
from check_core_owned_reset import test_models
from core_translation_words import normalize


def audit_bounded(add, operations):
    carrier = range(len(add))
    counts = Counter()
    for f, g in permutations(operations, 2):
        for a, b, z in product(carrier, repeat=3):
            t = add[a][b]
            assert add[t][f[a][g[b][z]]] == add[t][g[b][f[a][z]]]
            counts['observed_commutations'] += 1
    for t in carrier:
        above = [z for z in carrier if add[t][z] == z]
        index = {z: k for k, z in enumerate(above)}
        normalized = set()
        for a in carrier:
            if add[a][t] != t:
                continue
            for f in operations:
                values = tuple(add[t][f[a][z]] for z in above)
                assert all(add[value][z] == z for value, z in zip(values, above))
                normalized.add(tuple(index[value] for value in values))
        for E in normalized:
            assert compose(E, E) == E
            for F in normalized:
                assert compose(E, F) == compose(F, E)
                counts['normalized_map_pairs'] += 1
        composite = tuple(range(len(above)))
        for E in normalized:
            composite = compose(composite, E)
        common = [k for k in range(len(above)) if all(E[k] == k for E in normalized)]
        assert set(composite) == set(common)
        for k, z in enumerate(above):
            result = above[composite[k]]
            assert add[result][z] == z
            assert all(add[above[u]][result] == result
                       for u in common if add[above[u]][z] == z)
            counts['common_fixed_points'] += 1
    return counts


def audit(f, g, y):
    n = len(f)
    identity = tuple(range(n))
    G = tuple(g[y])
    generators = [(1 << a, tuple(f[a])) for a in range(n)] + [(0, G)]
    translations = dict(generators)
    counts = Counter(monoids=1)

    def translation(mask):
        if mask not in translations:
            bit = mask & -mask
            translations[mask] = compose(translation(bit), translation(mask ^ bit))
        return translations[mask]

    def evaluate(word):
        result = identity
        for token in word:
            result = compose(result, translation(token))
        return result

    def check_normal_form(word, value):
        normal = normalize(word)
        assert evaluate(normal) == value
        assert normalize(normal) == normal
        assert len(normal) <= 2 * n + 3
        positions = [i for i, token in enumerate(normal) if token == 0]
        if positions:
            internal = normal[positions[0] + 1:positions[-1]:2]
            assert all(a != b and a | b == b
                       for a, b in zip(internal, internal[1:]))
            assert len(internal) <= n

    representatives = {identity: ()}
    maps = [identity]
    for P in maps:
        square = compose(P, P)
        assert compose(square, P) == square
        counts['power_checks'] += 1
        for token, generator in generators:
            value = compose(P, generator)
            word = representatives[P] + (token,)
            check_normal_form(word, value)
            counts['normal_form_transitions'] += 1
            if value not in representatives:
                representatives[value] = word
                maps.append(value)

    sandwiches = {compose(compose(G, F), G) for _, F in generators}
    band = {compose(compose(G, P), G) for P in maps}
    assert G in band and sandwiches <= band
    for U in band:
        assert compose(U, U) == U
        assert compose(U, G) == compose(G, U) == U
        for V in band:
            UV = compose(U, V)
            assert UV in band
            assert compose(UV, U) == UV
            counts['band_products'] += 1

    # This intermediate equation is the arbitrary-word proof's only
    # additional reduction beyond the previous four-letter identities.
    R = [compose(compose(G, tuple(F)), G) for F in f]
    for a, b in product(range(n), repeat=2):
        assert compose(R[a], R[b]) == compose(R[a], R[f[a][b]])
        counts['prefix_equations'] += 1
    counts['monoid_elements'] = len(maps)
    counts['band_elements'] = len(band)
    return counts, len(maps), len(band)


def check():
    models = test_models()
    counts = Counter()
    max_monoid = max_band = 0
    for add, operations in models:
        counts.update(audit_bounded(add, operations))
        for f, g in permutations(operations, 2):
            for y in range(len(add)):
                result, size, band_size = audit(f, g, y)
                counts.update(result)
                max_monoid = max(max_monoid, size)
                max_band = max(max_band, band_size)
    assert normalize(()) == ()
    try:
        normalize((-1,))
    except ValueError:
        pass
    else:
        raise AssertionError('negative token accepted')
    print(f'Translation normal forms: {len(models)} models; '
          + ', '.join(f'{value} {key}' for key, value in sorted(counts.items()))
          + f'; largest monoid {max_monoid}, largest band {max_band}. '
          'All finite monoids were closed completely. General normalization '
          'and stabilization are written proofs; completeness of the core '
          'candidate is not asserted.')


if __name__ == '__main__':
    check()
