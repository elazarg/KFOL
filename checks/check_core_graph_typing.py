#!/usr/bin/env python3
"""Finite controls for the graph-cover core representation.

Replay the bounded control-set assignment on arbitrary coefficient values
of the published six-row source, then saturate the entire relation in the
old algebra times its atomic factor. Every pair above the old atomic ideal
must have its prescribed type. Cyclic control sets are outside this test.
Two explicit native-subpower covers are also checked on every product.
These finite checks do not replace the written arbitrary-girth proof.
"""
import itertools
import json
import time

import check_core_five_edge_countermodel as b

start = time.monotonic()
states, tables = b.coefficient_algebra()
n = 3
edges = ((0,1,0),(0,2,1),(1,3,1),(0,3,2),(1,2,2))
neighbors = {(u,i):v for u,v,i in edges} | {(v,i):u for u,v,i in edges}
profiles = [{i:{v for (v,j),w in neighbors.items() if j==i and s[w]==i} for i in range(3)} for s in states]
pivots = [{i for i in range(3) if s[4 if i<2 else 5]==i} for s in states]
eta = {c:next((i for i in range(3) if i in s),n) for c,s in enumerate(states) if 4 not in s}
counts = dict(attempted=0, forests=0, cyclic=0, relabelled=0, dual_pivot=0, relations=0, maximal_relation=0)
def assignment(gens):
    Z=set(); witnesses={}; mixed={}; pure={}; foreign={}
    for c in gens:
        active=[i for i in range(3) if profiles[c][i]]
        if len(active)>=2:
            v=next(iter(profiles[c][active[0]])); mixed[c]=v; Z.add(v)
        elif active:
            j=active[0]; pure[c]=j
            fp=pivots[c]-{j}; assert len(fp)<=1
            if fp: foreign[c]=next(iter(fp))
        elif len(pivots[c])==2:
            v=next(v for v in (2,3) if states[c][v]==4)
            witnesses[c]=v; Z.add(v)
    while True:
        support=next((profiles[c][pure[c]] for c in foreign if not profiles[c][pure[c]]<=Z and len(profiles[c][pure[c]])<=len(Z)),None)
        if support is None: break
        Z.update(support)
    colors={}
    for root in sorted(Z):
        if root in colors: continue
        colors[root]=n; stack=[(root,None)]
        while stack:
            v,parent=stack.pop()
            for u,w,i in edges:
                if v not in (u,w): continue
                other=w if u==v else u
                if other not in Z or other==parent: continue
                if other in colors: return None
                colors[other]=i; stack.append((other,v))
    labs={0:n}
    for c in gens:
        if c in mixed: lab=colors[mixed[c]]
        elif c in pure:
            lab=pure[c]
            if c in foreign and all(colors.get(v)==foreign[c] for v in profiles[c][pure[c]]):
                lab=foreign[c]; counts['relabelled']+=1
        elif c in witnesses:
            lab=colors[witnesses[c]]; counts['dual_pivot']+=1
        else: lab=next(iter(pivots[c]),n)
        if c==0: assert lab==n
        labs[c]=lab
    return labs

def saturate(labs):
    vals=list(labs.items()); seen=set(vals); pos=0
    while pos<len(vals):
        x,a=vals[pos]
        assert x not in eta or eta[x]==a, (x,a,eta.get(x),labs)
        for y,z in vals[:pos+1]:
            for h in range(4):
                c=tables[h][x][y]; atom=b.scalar(h,a,z)
                assert c not in eta or eta[c]==atom, (c,atom,eta.get(c),labs)
                pair=(c,atom)
                if pair not in seen: seen.add(pair); vals.append(pair)
        pos+=1
    return len(vals)

cases = [(c,) for c in range(192)]
cases += list(itertools.combinations(range(192), 2))
cases += [(c,(37*c+11)%192,(71*c+29)%192) for c in range(192)]
for gens in cases:
    counts['attempted']+=1
    labs=assignment(gens)
    if labs is None: counts['cyclic']+=1; continue
    counts['forests']+=1
    size=saturate(labs)
    counts['relations']+=size; counts['maximal_relation']=max(size,counts['maximal_relation'])
def verify_cover(gens):
    labs = assignment(gens)
    assert labs is not None
    pairs = list(labs.items()) + [(0, 4)]
    seen = set(pairs)
    position = 0
    while position < len(pairs):
        c, a = pairs[position]
        for d, z in pairs[:position + 1]:
            for h in range(4):
                item = (tables[h][c][d], b.scalar(h, a, z))
                if item not in seen:
                    seen.add(item)
                    pairs.append(item)
        position += 1
    clone = b.upper_clone(tables)
    epsilon = len(states)
    def image(pair):
        return epsilon if pair == (0, 4) else pair[0]
    products = 0
    for c, a in pairs:
        if a == 4 and c in eta:
            assert c == 0
        for d, z in pairs:
            for h in range(4):
                item = (tables[h][c][d], b.scalar(h, a, z))
                assert image(item) == clone[h][image((c,a))][image((d,z))]
                products += 1
    # Every old value generated by the coefficients is present without
    # the upper marker: the atomic part of the source is closed.
    old_values = {c for c, a in pairs if a != 4}
    assert {image(pair) for pair in pairs} == old_values | {epsilon}
    return dict(generators=gens, source_size=len(pairs),
                image_size=len(old_values)+1, products=products)

counts['covers'] = [verify_cover((1, 3, 4)), verify_cover((2, 3, 4))]
counts['seconds']=time.monotonic()-start
counts['scope']='All 192 singleton coefficients, all 18336 coefficient pairs, and 192 fixed triples in existing six-row source; only forest control sets tested. Finite diagnostic, not uniform theorem.'
print(json.dumps(counts,indent=2))
