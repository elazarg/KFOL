#!/usr/bin/env python3
"""Independent finite check of the global exhaustion-divisor construction.

Bases: D_K and U_K; direct products and
subpowers generated by the supplied failure. Assertions inspect every element
and operation of the constructed witness subalgebra, rather than trusting an
assumed normal form. The check concerns exact finite algebras, not a proof of
the universal theorem. Run with:
    python checks/check_core_exhaustion_divisor.py
"""
from itertools import product
from functools import reduce
from random import Random
from hashlib import sha256
import json

class Base:
    def __init__(self,k,kind):
        self.k,self.kind=k,kind
        if kind=='D':
            self.carrier=tuple(range(k+2)); self.atoms=tuple(range(k)); self.n=k; self.p=k+1
        else:
            self.carrier=tuple(range(1,(1<<k)+1)); self.atoms=tuple(1<<i for i in range(k)); self.n=(1<<k)-1; self.p=1<<k
    def join(self,a,b):
        if self.kind=='D':
            if a==b:return a
            if self.p in (a,b):return self.p
            return self.n
        return self.p if self.p in (a,b) else a|b
    def choice(self,i,a,b):
        return self.atoms[i] if self.atoms[i] in (a,b) else self.join(a,b)

class Power:
    def __init__(self,bases):
        self.bases=bases; self.k=bases[0].k
        assert all(b.k==self.k for b in bases)
    def join(self,a,b):return tuple(B.join(x,y) for B,x,y in zip(self.bases,a,b))
    def choice(self,i,a,b):return tuple(B.choice(i,x,y) for B,x,y in zip(self.bases,a,b))
    def joins(self,seq):return reduce(self.join,seq)
    def closure(self,gens):
        s=set(gens); todo=list(gens)
        while todo:
            a=todo.pop()
            for b in tuple(s):
                for v in [self.join(a,b)]+[self.choice(i,a,b) for i in range(self.k)]:
                    if v not in s:s.add(v);todo.append(v)
        return s

certificate=sha256(); counts={}; stats={}

def inspect(A,c,xs,label,check_generated=False):
    k=A.k
    bs=[A.choice(i,c,xs[i]) for i in range(k)]
    n=A.joins(bs); p=A.join(c,n)
    assert n!=p, ('input is not failure',label,c,xs)
    atoms=[A.choice(i,bs[i],p) for i in range(k)]
    assert A.joins(atoms)==n
    for i in range(k):
        assert A.choice(i,atoms[i],p)==atoms[i]
        for j in range(k):
            if i!=j:
                assert A.choice(i,atoms[j],p)==p
                assert A.choice(i,atoms[i],atoms[j])==atoms[i]
    images={p:k+1}
    for mask in range(1,1<<k):
        value=A.joins([atoms[i] for i in range(k) if mask>>i&1])
        im=(mask.bit_length()-1) if mask.bit_count()==1 else k
        if value in images:assert images[value]==im
        images[value]=im
    S=set(images)
    assert len(S)<=1<<k
    assert set(images.values())==set(range(k+2))
    D=Base(k,'D')
    for a in S:
        for b in S:
            v=A.join(a,b)
            assert v in S and images[v]==D.join(images[a],images[b])
            for i in range(k):
                v=A.choice(i,a,b)
                assert v in S and images[v]==D.choice(i,images[a],images[b])
    assert A.closure([p]+atoms)==S
    if check_generated:
        ambient=A.closure([c]+list(xs))
        assert S<=ambient
    counts[label]=counts.get(label,0)+1
    stats.setdefault(label,{'min_witness':len(S),'max_witness':len(S)})
    stats[label]['min_witness']=min(stats[label]['min_witness'],len(S))
    stats[label]['max_witness']=max(stats[label]['max_witness'],len(S))
    certificate.update(repr((label,c,xs,sorted(images.items()))).encode())

def all_failures_by_coordinate(bases,label):
    """Exact list: a failure has c=p, x_i=a_i in at least one coordinate.
    This native test is independent of the witness construction under test.
    Deduplicate tuples witnessing failure at more than one coordinate.
    """
    k=bases[0].k; A=Power(bases); seen=set()
    for active,B in enumerate(bases):
        other=[j for j in range(len(bases)) if j!=active]
        choices=[tuple(product(bases[j].carrier,repeat=k+1)) for j in other]
        for columns in product(*choices):
            cols={j:col for j,col in zip(other,columns)}
            cols[active]=(B.p,)+B.atoms
            rows=tuple(tuple(cols[j][r] for j in range(len(bases))) for r in range(k+1))
            if rows not in seen:
                seen.add(rows);inspect(A,rows[0],rows[1:],label)
    return len(seen)

for k in range(3,7):
    for kind in ('D','U'):
        b=Base(k,kind)
        inspect(Power([b]),(b.p,),tuple((a,) for a in b.atoms),f'{kind}{k}')
        # For U the sharpness witness is the entire 2^K-element algebra.
        if kind=='U':assert stats[f'U{k}']['max_witness']==1<<k

assert all_failures_by_coordinate([Base(3,'D')]*2,'D3^2')==2*5**4-1
assert all_failures_by_coordinate([Base(3,'U')]*2,'U3^2')==2*8**4-1
assert all_failures_by_coordinate([Base(3,'D'),Base(3,'U')],'D3xU3')==5**4+8**4-1
# Independent exhaustive scan confirms the coordinate characterization for D3^2.
B=Base(3,'D'); A=Power([B,B]); carrier=list(product(B.carrier,repeat=2)); actual=0
for rows in product(carrier,repeat=4):
    c=rows[0];n=A.joins([A.choice(i,c,rows[i+1]) for i in range(3)])
    if A.join(c,n)!=n:actual+=1
assert actual==counts['D3^2']

rng=Random(971923)
for k,dim,reps in [(3,3,100),(3,5,100),(4,2,100),(4,4,100),(5,2,50)]:
    for trial in range(reps):
        bases=[Base(k,rng.choice(('D','U'))) for _ in range(dim)]; A=Power(bases)
        active=rng.randrange(dim)
        cols=[tuple(rng.choice(B.carrier) for _ in range(k+1)) for B in bases]
        cols[active]=(bases[active].p,)+bases[active].atoms
        rows=tuple(tuple(cols[j][r] for j in range(dim)) for r in range(k+1))
        inspect(A,rows[0],rows[1:],f'random_K{k}_dim{dim}',check_generated=(k==3 and dim==3 and trial<10))

result={'status':'all assertions passed','counts':counts,'witness_sizes':stats,'certificate_sha256':certificate.hexdigest(),'scope':'D_K and U_K; all failures in D3^2,U3^2,D3xU3; seeded mixed powers and ten generated subpowers. No claim of general theorem proved by testing.'}
print(json.dumps(result,indent=2))
