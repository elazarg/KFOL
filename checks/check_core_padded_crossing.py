#!/usr/bin/env python3
"""Verify the finite premises of the padded-crossing countermodel proof.

The coefficient algebra is generated by nine explicit columns in a product
of sixteen proper native observers. Its carrier is NOT enumerated here.
The protected-path premises checked below justify the written inductions
that its entire P-free ideal is exactly {T,S,e}. The proved rigid-clone
criterion then supplies Gamma, ordered M, and E3 for its upper clone.

The failed native-valid identity uses nine variables (u,a,b,c,d,p,q,r,s):
  u <= f(u, f(h(a,b,p),h(c,d,q)))
       + g(u, g(h(a,c,r),h(b,d,s))).
Also checks the ordered-probe premises on five rectangular grids and
finite Boolean rules for the duplicate-profile local-typing induction.
These are proof-premise checks; no algebra carrier is enumerated.
Standard library only; no solver, external data, or depth-limited closure.
"""

from itertools import combinations, product
import json


ALPHA, BETA, GAMMA, NEUTRAL, UPPER = range(5)
VARIABLES = tuple("abcdpqrs")
POSITION = {name: index for index, name in enumerate(VARIABLES)}
F_BLOCKS = (frozenset("abp"), frozenset("cdq"))
G_BLOCKS = (frozenset("acr"), frozenset("bds"))
CORE = frozenset("abcd")


def native_tables():
    join = [[x if x == y else max(NEUTRAL, x, y)
             for y in range(5)] for x in range(5)]
    choices = [
        [[owner if owner in (x, y) else join[x][y]
          for y in range(5)] for x in range(5)]
        for owner in range(3)
    ]
    return choices + [join]


def fold(table, values):
    iterator = iter(values)
    result = next(iterator)
    for value in iterator:
        result = table[result][value]
    return result


def block_index(blocks, variable):
    return next(index for index, block in enumerate(blocks) if variable in block)


def construct_rows():
    rows = []
    centers = {}
    annotations = {}
    for owner, blocks, opposite, padding in (
        (ALPHA, F_BLOCKS, G_BLOCKS, ("r", "s")),
        (BETA, G_BLOCKS, F_BLOCKS, ("p", "q")),
    ):
        for index, block in enumerate(blocks):
            for variable in sorted(block):
                values = {name: NEUTRAL for name in VARIABLES}
                for name in blocks[1 - index]:
                    values[name] = owner
                values[variable] = UPPER
                if variable in CORE:
                    values[padding[block_index(opposite, variable)]] = GAMMA
                centers[owner, variable] = len(rows)
                rows.append(tuple(values[name] for name in VARIABLES))
    for variable in sorted(CORE):
        values = {name: NEUTRAL for name in VARIABLES}
        values[variable] = UPPER
        values[("p", "q")[block_index(F_BLOCKS, variable)]] = GAMMA
        values[("r", "s")[block_index(G_BLOCKS, variable)]] = GAMMA
        annotations[variable] = len(rows)
        rows.append(tuple(values[name] for name in VARIABLES))
    return rows, centers, annotations


def evaluate_targets(tables, values):
    f, g, h, _ = tables
    block_value = lambda block: fold(h, (values[POSITION[v]] for v in sorted(block)))
    return (f[block_value(F_BLOCKS[0])][block_value(F_BLOCKS[1])],
            g[block_value(G_BLOCKS[0])][block_value(G_BLOCKS[1])])


def owned_inputs(row, owner):
    return frozenset(v for v in VARIABLES if row[POSITION[v]] == owner)


def check_boolean_path_rules():
    """Local rules used by the general common-source/path inductions."""
    common_source_cases = 0
    for operation in range(4):
        for length in range(1, 4):
            for required in combinations(range(3), length):
                for left, right in product(product((0, 1), repeat=3), repeat=2):
                    output = tuple(
                        (left[i] | right[i]) if operation == i else (left[i] & right[i])
                        for i in range(3)
                    )
                    if all(output[i] for i in required):
                        assert (all(left[i] for i in required)
                                or all(right[i] for i in required))
                    common_source_cases += 1
    signed_path_cases = 0
    for selected in (False, True):
        for ep, en, fp, fn in product((0, 1), repeat=4):
            positive = (ep | fp) if selected else (ep & fp)
            negative_test = (en | fn) if selected else (en & fn)
            if positive and not negative_test:
                assert (ep and not en) or (fp and not fn)
                if selected:
                    assert not en and not fn
                else:
                    assert ep and fp
            signed_path_cases += 1
    return common_source_cases, signed_path_cases


def check_rectangle(tables, row_count, column_count):
    """Check all finite protected-path premises of one generalized grid.

    This checks a coordinate template, not its generated algebra carrier.
    The all-term conclusion is the written induction, not a finite-depth
    search. Ordered opposing blocks are retained individually.
    """
    f, g, h, join = tables
    core = {(i, j): "x%d_%d" % (i, j)
            for i in range(row_count) for j in range(column_count)}
    a = tuple("a%d" % i for i in range(row_count))
    b = tuple("b%d" % j for j in range(column_count))
    variables = tuple(core.values()) + a + b
    position = {v: k for k, v in enumerate(variables)}
    f_blocks = tuple(frozenset([core[i, j] for j in range(column_count)] + [a[i]])
                     for i in range(row_count))
    g_blocks = tuple(frozenset([core[i, j] for i in range(row_count)] + [b[j]])
                     for j in range(column_count))
    inverse_core = {v: ij for ij, v in core.items()}
    rows, row_owners, centers, annotations = [], [], {}, {}
    for owner, blocks in ((ALPHA, f_blocks), (BETA, g_blocks)):
        for source_index, block in enumerate(blocks):
            for opponent in range(len(blocks)):
                if source_index == opponent:
                    continue
                for v in sorted(block):
                    values = dict.fromkeys(variables, NEUTRAL)
                    for w in blocks[opponent]:
                        values[w] = owner
                    values[v] = UPPER
                    if v in inverse_core:
                        i, j = inverse_core[v]
                        values[b[j] if owner == ALPHA else a[i]] = GAMMA
                    centers[owner, source_index, opponent, v] = len(rows)
                    row_owners.append(owner)
                    rows.append(tuple(values[w] for w in variables))
    for (i, j), v in core.items():
        values = dict.fromkeys(variables, NEUTRAL)
        values[v], values[a[i]], values[b[j]] = UPPER, GAMMA, GAMMA
        annotations[i, j] = len(rows)
        row_owners.append(None)
        rows.append(tuple(values[w] for w in variables))
    expected = (row_count * (row_count - 1) * (column_count + 1)
                + column_count * (column_count - 1) * (row_count + 1)
                + row_count * column_count)
    assert len(rows) == len(set(rows)) == expected
    assert all(row.count(UPPER) == 1 for row in rows)
    assert all(len(set(row) & {ALPHA, BETA, GAMMA}) <= 2 for row in rows)
    owned = lambda row, owner: frozenset(
        v for v in variables if row[position[v]] == owner)
    assert {owned(row, ALPHA) for row in rows} - {frozenset()} == set(f_blocks)
    assert {owned(row, BETA) for row in rows} - {frozenset()} == set(g_blocks)
    t, s = [], []
    for row, owner in zip(rows, row_owners):
        h_value = lambda block: fold(h, (row[position[v]] for v in sorted(block)))
        first = fold(f, (h_value(block) for block in f_blocks))
        second = fold(g, (h_value(block) for block in g_blocks))
        assert first == (ALPHA if owner == ALPHA else NEUTRAL)
        assert second == (BETA if owner == BETA else NEUTRAL)
        assert join[first][second] == NEUTRAL
        t.append(first)
        s.append(second)
    h_supports = {owned(row, GAMMA) for row in rows} - {frozenset()}
    assert h_supports == ({frozenset((v,)) for v in a + b}
                          | {frozenset((v, w)) for v in a for w in b})
    h_protection = 0
    for support in h_supports:
        for v in support:
            owner, blocks, source_index = ((ALPHA, f_blocks, a.index(v))
                if v in a else (BETA, g_blocks, b.index(v)))
            for opponent in range(len(blocks)):
                if opponent == source_index:
                    continue
                row = rows[centers[owner, source_index, opponent, v]]
                assert row[position[v]] == UPPER and not owned(row, GAMMA)
                assert not support & owned(row, ALPHA)
                assert not support & owned(row, BETA)
                h_protection += 1
    mixed_protection = duplicate_annotation = 0
    for i, first in enumerate(f_blocks):
        for j, second in enumerate(g_blocks):
            assert first & second == {core[i, j]}
            row = rows[annotations[i, j]]
            assert row[position[core[i, j]]] == UPPER
            assert not owned(row, ALPHA) and not owned(row, BETA)
            assert not first & second & owned(row, GAMMA)
            mixed_protection += 1
            # Duplicate-profile typing uses a DIFFERENT row/column block.
            for k, block in enumerate(f_blocks):
                if k != i:
                    assert not block & owned(row, GAMMA)
                    duplicate_annotation += 1
            for ell, block in enumerate(g_blocks):
                if ell != j:
                    assert not block & owned(row, GAMMA)
                    duplicate_annotation += 1
    signed_protection = 0
    for (owner, source_index, opponent, v), index in centers.items():
        blocks = f_blocks if owner == ALPHA else g_blocks
        row = rows[index]
        assert row[position[v]] == UPPER
        assert owned(row, owner) == blocks[opponent]
        assert not blocks[source_index] & blocks[opponent]
        for foreign in set(range(3)) - {owner}:
            assert not blocks[source_index] & owned(row, foreign)
        signed_protection += 1
    ideal = tuple(t), tuple(s), (NEUTRAL,) * len(rows)
    labels = ALPHA, BETA, NEUTRAL
    for table in tables:
        for x, y in product(range(3), repeat=2):
            output = tuple(table[a0][b0] for a0, b0 in zip(ideal[x], ideal[y]))
            assert output == ideal[labels.index(table[labels[x]][labels[y]])]
    return {
        "rectangle": [row_count, column_count], "source_rows": len(rows),
        "coefficient_generators": len(variables) + 1,
        "carrier_enumerated": False, "h_supports": len(h_supports),
        "h_protection": h_protection, "mixed_annotations": mixed_protection,
        "signed_protection": signed_protection,
        "duplicate_annotation_protection": duplicate_annotation,
    }


def check_duplicate_typing_rules(tables):
    """Local Boolean induction rules, not a generated-algebra census.

    The assignment 10->alpha, 01->beta, 00/11->n is rounded downward
    in both ownership bits. Therefore it never gives an old neutral term
    a spurious owner. A positive-old/negative-new path ends at 11;
    annotation protection in check_rectangle rules out such a path for
    an actually atomic old output.
    """
    labels = ALPHA, BETA, NEUTRAL
    label_for = {(0, 0): NEUTRAL, (1, 0): ALPHA,
                 (0, 1): BETA, (1, 1): NEUTRAL}
    leaf_cases = 0
    for bits, label in label_for.items():
        for owner in (ALPHA, BETA):
            assert int(label == owner) <= bits[owner]
            if bits[owner] and label != owner:
                assert bits == (1, 1)
            leaf_cases += 1
    # Every possible intermediate state respecting the two inequalities.
    states = [(first, second, label)
              for first, second in product((0, 1), repeat=2)
              for label in labels
              if int(label == ALPHA) <= first and int(label == BETA) <= second]
    assert len(states) == 8
    monotonic_cases = signed_cases = 0
    for operation, table in enumerate(tables):
        for left, right in product(states, repeat=2):
            old = tuple((left[i] | right[i]) if operation == i
                        else (left[i] & right[i]) for i in (ALPHA, BETA))
            new_label = table[left[2]][right[2]]
            for owner in (ALPHA, BETA):
                assert int(new_label == owner) <= old[owner]
                monotonic_cases += 1
                if old[owner] and new_label != owner:
                    assert ((left[owner] and left[2] != owner)
                            or (right[owner] and right[2] != owner))
                    if operation == owner:
                        assert left[2] != owner and right[2] != owner
                    else:
                        assert left[owner] and right[owner]
                signed_cases += 1
    # Exhaust all profile lists just above the pigeonhole bound for m<=2.
    # This supplements the general 2^m counting argument in the proof.
    duplicate_lists = 0
    for generator_count in range(3):
        profiles = tuple(product((0, 1), repeat=generator_count))
        for sequence in product(profiles, repeat=len(profiles) + 1):
            first_position = {}
            duplicate = None
            for index, profile in enumerate(sequence):
                if profile in first_position:
                    duplicate = first_position[profile], index
                    break
                first_position[profile] = index
            assert duplicate is not None
            i, k = duplicate
            assert i != k and sequence[i] == sequence[k]
            duplicate_lists += 1
    return {"initial_leaf_cases": leaf_cases,
            "profile_monotonicity_cases": monotonic_cases,
            "signed_path_cases": signed_cases,
            "exhaustive_duplicate_lists_m_le_2": duplicate_lists}


def main():
    tables = native_tables()
    f, g, h, join = tables
    rows, centers, annotations = construct_rows()
    assert len(rows) == len(set(rows)) == 16
    assert all(len(set(row) & {ALPHA, BETA, GAMMA}) <= 2 for row in rows)
    assert all(row.count(UPPER) == 1 for row in rows)
    targets = [evaluate_targets(tables, row) for row in rows]
    t = tuple(value[0] for value in targets)
    s = tuple(value[1] for value in targets)
    e = (NEUTRAL,) * 16
    assert t == (ALPHA,) * 6 + (NEUTRAL,) * 10
    assert s == (NEUTRAL,) * 6 + (BETA,) * 6 + (NEUTRAL,) * 4
    assert tuple(join[x][y] for x, y in zip(t, s)) == e

    # Ownership detection and P-retention, for every native operation.
    ownership_entries = 0
    persistence_entries = 0
    for operation, table in enumerate(tables):
        for x, y in product(range(5), repeat=2):
            for owner in range(3):
                expected = ((x == owner or y == owner) if operation == owner
                            else (x == owner and y == owner))
                assert (table[x][y] == owner) == expected
                ownership_entries += 1
        for other in range(5):
            if operation == 3 or other != operation:
                assert table[UPPER][other] == UPPER
                persistence_entries += 1

    # Every actual h-support is protected by its private centers.
    h_supports = {owned_inputs(row, GAMMA) for row in rows} - {frozenset()}
    expected_h_supports = {frozenset(v) for v in "pqrs"} | {
        frozenset((x, y)) for x, y in product("pq", "rs")
    }
    assert h_supports == expected_h_supports
    h_protection_entries = 0
    for support in h_supports:
        for variable in support:
            owner = ALPHA if variable in "pq" else BETA
            row = rows[centers[owner, variable]]
            assert row[POSITION[variable]] == UPPER
            assert not owned_inputs(row, GAMMA)
            for foreign in (ALPHA, BETA):
                assert not support & owned_inputs(row, foreign)
                h_protection_entries += 1

    # Mixed f/g profiles are protected at their unique annotation vertex.
    assert {owned_inputs(row, ALPHA) for row in rows} - {frozenset()} == set(F_BLOCKS)
    assert {owned_inputs(row, BETA) for row in rows} - {frozenset()} == set(G_BLOCKS)
    annotation_entries = 0
    for left, right in product(F_BLOCKS, G_BLOCKS):
        intersection = left & right
        assert len(intersection) == 1
        variable = next(iter(intersection))
        row = rows[annotations[variable]]
        assert row[POSITION[variable]] == UPPER
        assert not owned_inputs(row, ALPHA) and not owned_inputs(row, BETA)
        assert not intersection & owned_inputs(row, GAMMA)
        annotation_entries += 1

    # A positive block/negative opposite block cannot give a P-free term.
    signed_protection_entries = 0
    for owner, blocks in ((ALPHA, F_BLOCKS), (BETA, G_BLOCKS)):
        for index, positive in enumerate(blocks):
            negative = blocks[1 - index]
            assert not positive & negative
            for variable in positive:
                row = rows[centers[owner, variable]]
                assert row[POSITION[variable]] == UPPER
                assert owned_inputs(row, owner) == negative
                for foreign in set(range(3)) - {owner}:
                    assert not positive & owned_inputs(row, foreign)
                    signed_protection_entries += 1
    common_source_cases, signed_path_cases = check_boolean_path_rules()

    # The three exact P-free vectors have the flat two-owner atomic table.
    ideal = (t, s, e)
    atomic_labels = (ALPHA, BETA, NEUTRAL)
    ideal_entries = 0
    for table in tables:
        for x, y in product(range(3), repeat=2):
            output = tuple(table[a][b] for a, b in zip(ideal[x], ideal[y]))
            expected = table[atomic_labels[x]][atomic_labels[y]]
            assert output == ideal[atomic_labels.index(expected)]
            ideal_entries += 1
    reflection_entries = 0
    for table in tables:
        for x in range(5):
            assert (join[NEUTRAL][table[NEUTRAL][x]] == NEUTRAL) == (x != UPPER)
            reflection_entries += 1
    prime_entries = 0
    for table in tables:
        for x, y in product(atomic_labels, repeat=2):
            first, second = table[NEUTRAL][x], table[NEUTRAL][y]
            if join[first][second] == NEUTRAL:
                assert NEUTRAL in (first, second)
            prime_entries += 1
    assert all(sum(table[NEUTRAL][x] != NEUTRAL for table in tables[:3]) <= 1
               for x in atomic_labels)
    assert all(h[NEUTRAL][x] == NEUTRAL for x in atomic_labels)

    # Literal source quotient: P -> n is atomic, with common-join fibers.
    collapse = (ALPHA, BETA, GAMMA, NEUTRAL, NEUTRAL)
    collapse_entries = fiber_entries = 0
    for table in tables:
        for x, y in product(range(5), repeat=2):
            assert collapse[table[x][y]] == table[collapse[x]][collapse[y]]
            collapse_entries += 1
            if collapse[x] == collapse[y]:
                assert table[x][y] == join[x][y]
                fiber_entries += 1
        # Old marker tuples above e retain every marker under every operation.
        assert all(table[NEUTRAL][x] == x for x in (NEUTRAL, UPPER))

    # Exact atomic UNSAT, with neutral labels included.
    atomic_assignments = 0
    for values in product(atomic_labels, repeat=8):
        assert evaluate_targets(tables, values) != (ALPHA, BETA)
        atomic_assignments += 1

    # Full native coefficient check, then all source/output combinations.
    # Together these verify the nine-variable law without repeating source u
    # for each of the 5^8 coefficient assignments.
    native_coefficients = 0
    for values in product(range(5), repeat=8):
        assert evaluate_targets(tables, values) != (ALPHA, BETA)
        native_coefficients += 1
    source_cases = 0
    for u, first, second in product(range(5), repeat=3):
        bound = join[f[u][first]][g[u][second]]
        failure = join[u][bound] != bound
        assert failure == (u == UPPER and first == ALPHA and second == BETA)
        source_cases += 1

    # Rigid cloning turns the source into epsilon and keeps its two arms old.
    assert f[UPPER][ALPHA] == ALPHA and g[UPPER][BETA] == BETA
    assert join[ALPHA][BETA] == NEUTRAL != UPPER

    rectangles = [check_rectangle(tables, r, s)
                  for r, s in ((2, 2), (2, 3), (3, 2), (3, 3), (4, 5))]
    duplicate_typing = check_duplicate_typing_rules(tables)

    print(json.dumps({
        "status": "PASS", "source_rows": len(rows), "source_generators": 9,
        "rectangles": rectangles, "duplicate_typing": duplicate_typing,
        "carrier_enumerated": False, "native_ownership_entries": ownership_entries,
        "native_marker_persistence_entries": persistence_entries,
        "h_supports": len(h_supports), "h_protection_entries": h_protection_entries,
        "annotation_entries": annotation_entries,
        "signed_protection_entries": signed_protection_entries,
        "common_source_boolean_cases": common_source_cases,
        "signed_path_boolean_cases": signed_path_cases,
        "flat_ideal_entries": ideal_entries, "reflection_entries": reflection_entries,
        "prime_entries": prime_entries, "atomic_quotient_entries": collapse_entries,
        "common_fiber_entries": fiber_entries, "atomic_UNSAT_assignments": atomic_assignments,
        "full_native_coefficient_assignments": native_coefficients,
        "native_source_output_cases": source_cases, "failed_identity_variables": 9,
    }, sort_keys=True))


if __name__ == "__main__":
    main()
